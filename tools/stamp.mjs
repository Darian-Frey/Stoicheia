// stamp.mjs — version every module URL so updates never mix old and new code (BUG-005).
//
//   node tools/stamp.mjs           stamp a new version into every page
//   node tools/stamp.mjs --check   verify every page's import map is complete and current
//
// Each page in docs/ carries a block between <!-- stamp entry=js/NAME.js -->
// and <!-- /stamp --> holding an import map, the stylesheet link and the
// entry import. The map lists every module under docs/js/ and docs/data/
// with ?v=VERSION, so changing VERSION makes a browser fetch all of them
// afresh. The block is generated from the files on disk, so a new module or
// data file cannot be forgotten. Run it before every push that changes
// docs/. Author tooling only: the site runs without it (D-001).

import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const DOCS = resolve(fileURLToPath(new URL("../docs/", import.meta.url)));
const BLOCK = /<!-- stamp entry=(\S+) -->[\s\S]*?<!-- \/stamp -->/;

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else if (e.name.endsWith(".js")) out.push(p);
  }
  return out;
}

/** Every module the site can load, as page-relative paths ("./js/scene.js"). */
export async function modules() {
  const files = [...(await walk(join(DOCS, "js"))), ...(await walk(join(DOCS, "data")))];
  return files.map((f) => "./" + relative(DOCS, f).split("\\").join("/")).sort();
}

/** HTML pages carrying a stamp block. */
export async function pages() {
  const names = (await readdir(DOCS)).filter((n) => n.endsWith(".html")).sort();
  const out = [];
  for (const name of names) {
    const html = await readFile(join(DOCS, name), "utf8");
    const m = BLOCK.exec(html);
    out.push({ name, html, entry: m?.[1] ?? null });
  }
  return out;
}

export function block(entry, version, mods) {
  const imports = Object.fromEntries(mods.map((m) => [m, `${m}?v=${version}`]));
  const json = JSON.stringify({ imports }, null, 2).split("\n").join("\n");
  return [
    `<!-- stamp entry=${entry} -->`,
    `<!-- Generated by tools/stamp.mjs; do not edit by hand (BUG-005). -->`,
    `<script type="importmap">`,
    json,
    `</script>`,
    `<link rel="stylesheet" href="css/instrument.css?v=${version}">`,
    `<script type="module">import "./${entry}";</script>`,
    `<!-- /stamp -->`,
  ].join("\n");
}

/** The version a page is stamped with, or null. */
export function versionOf(html) {
  return /instrument\.css\?v=([^"]+)"/.exec(html)?.[1] ?? null;
}

/** Problems with the current stamps; empty when every page is complete and consistent. */
export async function problems() {
  const mods = await modules();
  const found = [];
  const versions = new Set();
  for (const p of await pages()) {
    if (!p.entry) { found.push(`${p.name}: no stamp block`); continue; }
    const v = versionOf(p.html);
    versions.add(v);
    if (BLOCK.exec(p.html)[0] !== block(p.entry, v, mods)) {
      found.push(`${p.name}: import map out of date (run node tools/stamp.mjs)`);
    }
  }
  if (versions.size > 1) found.push(`pages carry different versions: ${[...versions].join(", ")}`);
  return found;
}

function newVersion() {
  // UTC timestamp to the minute: unique per stamp, sortable, readable.
  return new Date().toISOString().slice(0, 16).replace(/[-:]/g, "");
}

async function stamp() {
  const mods = await modules();
  const version = newVersion();
  for (const p of await pages()) {
    if (!p.entry) { console.error(`${p.name}: no stamp block, skipped`); continue; }
    await writeFile(join(DOCS, p.name), p.html.replace(BLOCK, block(p.entry, version, mods)));
    console.log(`${p.name}: stamped ${version} (${mods.length} modules)`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const found = await problems();
    for (const f of found) console.error(f);
    console.log(found.length ? `${found.length} problem(s)` : "stamps ok");
    process.exit(found.length ? 1 : 0);
  } else {
    await stamp();
  }
}
